#!/usr/bin/env python
"""Prepare a server package from this addon repo for upload to AYON server.

Requires Python 3.9+.

Produces a ZIP file (default: ./package/{name}-{version}.zip) that can be
uploaded directly to an AYON server instance.

Usage
-----
  python create_package.py                   # build frontend + zip
  python create_package.py --skip-zip -o ./out   # folder only, no zip
  python create_package.py --debug           # verbose logging
"""

import argparse
import collections
import io
import json
import logging
import os
import platform
import re
import shutil
import subprocess
import sys
import zipfile
from typing import Iterable, List, Optional, Pattern, Tuple, Union

import package

FileMapping = Tuple[Union[str, io.BytesIO], str]

ADDON_NAME: str = package.name
ADDON_VERSION: str = package.version
ADDON_CLIENT_DIR: Union[str, None] = getattr(package, "client_dir", None)

CURRENT_ROOT: str = os.path.dirname(os.path.abspath(__file__))
SERVER_ROOT: str = os.path.join(CURRENT_ROOT, "server")
FRONTEND_ROOT: str = os.path.join(CURRENT_ROOT, "frontend")
FRONTEND_DIST_ROOT: str = os.path.join(FRONTEND_ROOT, "dist")
DST_DIST_DIR: str = os.path.join("frontend", "dist")
PRIVATE_ROOT: str = os.path.join(CURRENT_ROOT, "private")
PUBLIC_ROOT: str = os.path.join(CURRENT_ROOT, "public")

# Patterns of directories to skip when collecting server files
IGNORE_DIR_PATTERNS: List[Pattern] = [
    re.compile(p)
    for p in {r"^\.", "^__pycache__$"}
]

# Patterns of files to skip when collecting server files
IGNORE_FILE_PATTERNS: List[Pattern] = [
    re.compile(p)
    for p in {r"^\.", r"\.pyc$"}
]


# ── Utilities ─────────────────────────────────────────────────────────────────


class ZipFileLongPaths(zipfile.ZipFile):
    """ZipFile subclass that handles long paths on Windows."""

    _is_windows = platform.system().lower() == "windows"

    def _extract_member(self, member, tpath, pwd):
        if self._is_windows:
            tpath = os.path.abspath(tpath)
            if tpath.startswith("\\\\"):
                tpath = "\\\\?\\UNC\\" + tpath[2:]
            else:
                tpath = "\\\\?\\" + tpath
        return super()._extract_member(member, tpath, pwd)


def _get_yarn_executable() -> Optional[str]:
    cmd = "where" if platform.system().lower() == "windows" else "which"
    try:
        for line in subprocess.check_output(
            [cmd, "yarn"], encoding="utf-8"
        ).splitlines():
            if line and os.path.exists(line):
                try:
                    subprocess.call([line, "--version"])
                    return line
                except OSError:
                    continue
    except subprocess.CalledProcessError:
        pass
    return None


def _value_match_regexes(value: str, regexes: Iterable[Pattern]) -> bool:
    return any(regex.search(value) for regex in regexes)


def find_files_in_subdir(
    src_path: str,
    ignore_file_patterns: Optional[List[Pattern]] = None,
    ignore_dir_patterns: Optional[List[Pattern]] = None,
) -> List[Tuple[str, str]]:
    if ignore_file_patterns is None:
        ignore_file_patterns = IGNORE_FILE_PATTERNS
    if ignore_dir_patterns is None:
        ignore_dir_patterns = IGNORE_DIR_PATTERNS

    output: List[Tuple[str, str]] = []
    if not os.path.exists(src_path):
        return output

    queue: collections.deque = collections.deque()
    queue.append((src_path, []))
    while queue:
        dirpath, parents = queue.popleft()
        for name in os.listdir(dirpath):
            path = os.path.join(dirpath, name)
            if os.path.isfile(path):
                if not _value_match_regexes(name, ignore_file_patterns):
                    output.append((path, os.path.sep.join(parents + [name])))
            elif not _value_match_regexes(name, ignore_dir_patterns):
                queue.append((path, parents + [name]))

    return output


def safe_copy_file(src_path: str, dst_path: str) -> None:
    if src_path == dst_path:
        return
    os.makedirs(os.path.dirname(dst_path), exist_ok=True)
    shutil.copy2(src_path, dst_path)


# ── Build steps ───────────────────────────────────────────────────────────────


def update_frontend_version(log: logging.Logger) -> None:
    """Sync addonVersion.ts and package.json to the current package version."""
    version_file = os.path.join(FRONTEND_ROOT, "src", "addonVersion.ts")
    with open(version_file, "w") as fh:
        fh.write(
            "// Auto-generated by create_package.py — do not edit manually.\n"
            f'const addonVersion = "{ADDON_VERSION}"\n'
            "export default addonVersion\n"
        )

    pkg_path = os.path.join(FRONTEND_ROOT, "package.json")
    with open(pkg_path, "r") as fh:
        data = json.load(fh)
    data["version"] = ADDON_VERSION
    with open(pkg_path, "w") as fh:
        json.dump(data, fh, indent=2)
        fh.write("\n")

    log.info("Frontend version updated to %s", ADDON_VERSION)


def build_frontend(log: logging.Logger) -> None:
    yarn = _get_yarn_executable()
    if yarn is None:
        raise RuntimeError("Yarn executable not found. Install Node.js / Yarn.")

    log.info("Installing frontend dependencies…")
    subprocess.run([yarn, "install"], cwd=FRONTEND_ROOT, check=True)

    log.info("Building frontend…")
    subprocess.run([yarn, "build"], cwd=FRONTEND_ROOT, check=True)

    if not os.path.exists(FRONTEND_DIST_ROOT):
        raise RuntimeError(
            "Frontend build failed — dist/ directory not found."
        )

    log.info("Frontend build complete.")


# ── File mapping ──────────────────────────────────────────────────────────────


def get_base_files_mapping() -> List[FileMapping]:
    mapping: List[FileMapping] = [
        (os.path.join(CURRENT_ROOT, "package.py"), "package.py")
    ]

    license_path = os.path.join(CURRENT_ROOT, "LICENSE")
    if os.path.exists(license_path):
        mapping.append((license_path, "LICENSE"))

    for dirpath in (SERVER_ROOT, PRIVATE_ROOT, PUBLIC_ROOT):
        if not os.path.exists(dirpath):
            continue
        dirname = os.path.basename(dirpath)
        for src_file, subpath in find_files_in_subdir(dirpath):
            mapping.append((src_file, os.path.join(dirname, subpath)))

    if os.path.exists(FRONTEND_DIST_ROOT):
        for src_file, subpath in find_files_in_subdir(FRONTEND_DIST_ROOT):
            mapping.append((src_file, os.path.join(DST_DIST_DIR, subpath)))

    return mapping


# ── Output ────────────────────────────────────────────────────────────────────


def copy_addon_package(
    output_dir: str,
    files_mapping: List[FileMapping],
    log: logging.Logger,
) -> None:
    addon_output_dir = os.path.join(output_dir, ADDON_NAME, ADDON_VERSION)
    if os.path.isdir(addon_output_dir):
        log.info("Purging existing output at %s", addon_output_dir)
        shutil.rmtree(addon_output_dir)
    os.makedirs(addon_output_dir, exist_ok=True)

    for src_file, dst_subpath in files_mapping:
        dst_path = os.path.join(addon_output_dir, dst_subpath)
        os.makedirs(os.path.dirname(dst_path), exist_ok=True)
        if isinstance(src_file, io.BytesIO):
            with open(dst_path, "wb") as fh:
                fh.write(src_file.getvalue())
        else:
            safe_copy_file(src_file, dst_path)

    log.info("Package folder created at %s", addon_output_dir)


def create_addon_package(
    output_dir: str,
    files_mapping: List[FileMapping],
    log: logging.Logger,
) -> None:
    os.makedirs(output_dir, exist_ok=True)
    output_path = os.path.join(output_dir, f"{ADDON_NAME}-{ADDON_VERSION}.zip")

    with ZipFileLongPaths(output_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for src_file, dst_subpath in files_mapping:
            if isinstance(src_file, io.BytesIO):
                zf.writestr(dst_subpath, src_file.getvalue())
            else:
                zf.write(src_file, dst_subpath)

    log.info("Package ZIP created at %s", output_path)


# ── Entry point ───────────────────────────────────────────────────────────────


def main(
    output_dir: Optional[str] = None,
    skip_zip: bool = False,
) -> None:
    log = logging.getLogger("create_package")
    log.info("Starting package creation for %s %s", ADDON_NAME, ADDON_VERSION)

    if not output_dir:
        output_dir = os.path.join(CURRENT_ROOT, "package")

    update_frontend_version(log)
    build_frontend(log)

    files_mapping = get_base_files_mapping()

    if skip_zip:
        copy_addon_package(output_dir, files_mapping, log)
    else:
        create_addon_package(output_dir, files_mapping, log)

    log.info("Package creation finished.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--skip-zip",
        dest="skip_zip",
        action="store_true",
        help="Copy files into a folder instead of creating a ZIP.",
    )
    parser.add_argument(
        "-o",
        "--output",
        dest="output_dir",
        default=None,
        help="Directory where the package will be written (default: ./package).",
    )
    parser.add_argument(
        "--debug",
        dest="debug",
        action="store_true",
        help="Enable debug logging.",
    )

    args = parser.parse_args(sys.argv[1:])
    logging.basicConfig(level=logging.DEBUG if args.debug else logging.INFO)
    main(args.output_dir, args.skip_zip)
